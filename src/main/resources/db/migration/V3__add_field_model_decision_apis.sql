create table vents (
    id varchar(80) primary key,
    building_id varchar(30) not null references buildings(id),
    name varchar(100) not null,
    type varchar(40) not null,
    position_x double precision,
    position_y double precision,
    position_z double precision,
    coordinate_system varchar(40) not null default 'BUILDING_LOCAL_M',
    width_m double precision,
    height_m double precision,
    area_m2 double precision,
    direction_degrees double precision,
    status varchar(30) not null default 'UNKNOWN',
    source_type varchar(30) not null default 'ESTIMATED',
    last_surveyed_at timestamp with time zone,
    constraint ck_vent_area_positive check (area_m2 is null or area_m2 > 0)
);

create index idx_vents_building on vents(building_id);

create table sensors (
    id varchar(80) primary key,
    manufacturer varchar(100),
    model varchar(100),
    serial_number varchar(120) unique,
    measurement_types varchar(300) not null,
    minimum_value double precision,
    maximum_value double precision,
    accuracy_text varchar(200),
    calibrated_at timestamp with time zone,
    calibration_expires_at timestamp with time zone,
    status varchar(30) not null default 'UNKNOWN'
);

alter table measurements add column batch_id varchar(100);
alter table measurements add column client_record_id varchar(120);
create unique index uq_measurement_client_record on measurements(client_record_id);
create index idx_measurements_vent_time on measurements(vent_id, measured_at desc);
create index idx_measurements_sensor_time on measurements(sensor_id, measured_at desc);

create table measurement_quality_history (
    id bigint generated by default as identity primary key,
    measurement_id bigint not null references measurements(id),
    previous_flag varchar(30) not null,
    new_flag varchar(30) not null,
    reason varchar(500) not null,
    actor varchar(100) not null,
    changed_at timestamp with time zone not null default current_timestamp
);

create index idx_measurement_quality_history on measurement_quality_history(measurement_id, changed_at desc);

create table turbines (
    id varchar(80) primary key,
    manufacturer varchar(100),
    model varchar(100) not null,
    rotor_area_m2 double precision,
    cut_in_wind_speed_m_s double precision,
    rated_wind_speed_m_s double precision,
    rated_power_w double precision,
    cut_out_wind_speed_m_s double precision,
    generator_efficiency_percent double precision,
    curve_version varchar(80) not null,
    source varchar(500),
    valid_from date,
    verification_status varchar(30) not null default 'DRAFT'
);

create table turbine_power_curve_points (
    id bigint generated by default as identity primary key,
    turbine_id varchar(80) not null references turbines(id),
    wind_speed_m_s double precision not null,
    power_w double precision not null,
    constraint uq_turbine_curve_speed unique (turbine_id, wind_speed_m_s),
    constraint ck_curve_values_nonnegative check (wind_speed_m_s >= 0 and power_w >= 0)
);

create table reference_factors (
    id bigint generated by default as identity primary key,
    type varchar(40) not null,
    factor_value double precision not null,
    unit varchar(60) not null,
    source_name varchar(200) not null,
    source_url varchar(600),
    valid_from date,
    valid_to date,
    version varchar(80) not null,
    scope varchar(100) not null default 'DEMO',
    status varchar(30) not null default 'DRAFT',
    constraint uq_reference_factor_version unique (type, version)
);

create table validations (
    id varchar(80) primary key,
    building_id varchar(30) not null references buildings(id),
    vent_id varchar(80) not null,
    prediction_model_version varchar(120) not null,
    sample_count integer not null,
    mae_w double precision not null,
    rmse_w double precision not null,
    mape_percent double precision,
    bias_w double precision not null,
    status varchar(30) not null,
    thresholds_configured boolean not null default false,
    passed boolean,
    created_at timestamp with time zone not null default current_timestamp
);

create table decisions (
    id varchar(80) primary key,
    candidate_id varchar(180) not null,
    status varchar(30) not null,
    reason varchar(1000) not null,
    assignee varchar(100),
    due_at timestamp with time zone,
    evidence_snapshot varchar(4000) not null,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp
);

create index idx_decisions_candidate on decisions(candidate_id, updated_at desc);

create table decision_history (
    id bigint generated by default as identity primary key,
    decision_id varchar(80) not null references decisions(id),
    previous_status varchar(30) not null,
    new_status varchar(30) not null,
    reason varchar(1000) not null,
    actor varchar(100) not null,
    changed_at timestamp with time zone not null default current_timestamp
);

create index idx_decision_history on decision_history(decision_id, changed_at desc);

