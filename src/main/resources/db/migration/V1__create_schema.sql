create table buildings (
    id varchar(30) primary key,
    name varchar(80) not null,
    code varchar(40) not null,
    map_x double precision not null,
    map_y double precision not null,
    priority_rank integer not null,
    model_type varchar(30) not null,
    advice varchar(500) not null,
    data_status varchar(30) not null
);

create table hourly_wind_densities (
    id bigint generated by default as identity primary key,
    building_id varchar(30) not null references buildings(id),
    hour_of_day integer not null,
    density_w_m2 double precision not null,
    source_type varchar(30) not null default 'TEST_PDF',
    constraint uq_density_building_hour unique (building_id, hour_of_day),
    constraint ck_density_hour check (hour_of_day between 0 and 23),
    constraint ck_density_nonnegative check (density_w_m2 >= 0)
);

create table measurements (
    id bigint generated by default as identity primary key,
    building_id varchar(30) not null references buildings(id),
    vent_id varchar(80) not null,
    measured_at timestamp with time zone not null,
    timezone varchar(60) not null,
    wind_speed_m_s double precision not null,
    vent_area_m2 double precision not null,
    sensor_id varchar(80) not null,
    quality_flag varchar(30) not null,
    operating_state varchar(30) not null,
    created_at timestamp with time zone not null default current_timestamp,
    constraint ck_measurement_speed_nonnegative check (wind_speed_m_s >= 0),
    constraint ck_measurement_area_positive check (vent_area_m2 > 0)
);

create index idx_measurements_building_time on measurements(building_id, measured_at desc);

